#!/usr/bin/env python3
"""Generate the Mac app's Localizable.strings (en, fr) from the Windows app's Strings.cs.

One source of truth for the UI text: edit Strings.cs, then run
    python3 tools/gen-mac-strings.py
"PC" wording becomes "Mac", {0} placeholders become %1$@, and the Mac-only keys below are added.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src/AndroidTVDebloater/Localization/Strings.cs"
OUT = ROOT / "mac/Resources"

MAC_ONLY = {
    "en": {
        "Mac_CheckForUpdatesMenu": "Check for Updates…",
        "Mac_Steps": "Steps",
        "Mac_Tools": "Tools",
        "Mac_ShowInFinder": "Show in Finder",
    },
    "fr": {
        "Mac_CheckForUpdatesMenu": "Rechercher les mises à jour…",
        "Mac_Steps": "Étapes",
        "Mac_Tools": "Outils",
        "Mac_ShowInFinder": "Afficher dans le Finder",
    },
}

# Wording that differs on a Mac. Applied in order, whole words only.
REPLACE = {
    "en": [("this PC", "this Mac"), ("the PC", "the Mac"), ("on PC", "on Mac"), ("PC", "Mac")],
    "fr": [("ce PC", "ce Mac"), ("le PC", "le Mac"), ("du PC", "du Mac"), ("PC", "Mac")],
}


def tables(text: str) -> dict[str, dict[str, str]]:
    out = {}
    for lang, name in (("en", "En"), ("fr", "Fr")):
        start = text.index(f"Dictionary<string, string> {name} = new()")
        body = text[start: text.index("};", start)]
        entries = {}
        for m in re.finditer(r'\["(\w+)"\]\s*=\s*"((?:[^"\\]|\\.)*)"', body):
            entries[m.group(1)] = m.group(2).replace('\\"', '"').replace("\\\\", "\\")
        out[lang] = entries
    return out


def to_mac(lang: str, s: str) -> str:
    for old, new in REPLACE[lang]:
        s = re.sub(rf"\b{re.escape(old)}\b", new, s)
    # String.Format placeholders → positional printf placeholders.
    s = s.replace("%", "%%")
    return re.sub(r"\{(\d+)\}", lambda m: f"%{int(m.group(1)) + 1}$@", s)


def escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main() -> None:
    t = tables(SRC.read_text(encoding="utf-8"))
    for lang in ("en", "fr"):
        entries = {k: to_mac(lang, v) for k, v in t[lang].items()}
        # A key missing in French falls back to English, like on Windows.
        for k, v in t["en"].items():
            entries.setdefault(k, to_mac("en", v))
        entries.update(MAC_ONLY[lang])
        lines = ["/* Generated by tools/gen-mac-strings.py from Strings.cs. Do not edit. */", ""]
        lines += [f'"{k}" = "{escape(v)}";' for k, v in sorted(entries.items())]
        folder = OUT / f"{lang}.lproj"
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{lang}: {len(entries)} strings")


if __name__ == "__main__":
    main()
